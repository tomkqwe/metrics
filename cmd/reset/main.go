// Command reset generates Reset methods for structs marked with // generate:reset.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const generatedHeader = "// Code generated by cmd/reset; DO NOT EDIT.\n"

func main() {
	if err := generate("."); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// generate loads all buildable packages below root using the current Go build
// configuration. Dependencies and test files are not generation targets.
func generate(root string) error {
	pkgs, err := packages.Load(&packages.Config{
		Dir: root,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps,
	}, "./...")
	if err != nil {
		return fmt.Errorf("load packages: %w", err)
	}
	// Prepare every output before writing, so invalid input cannot partially update files.
	outputs := make(map[string][]byte)
	for _, pkg := range pkgs {
		if len(pkg.Errors) != 0 {
			return fmt.Errorf("load %s: %s", pkg.PkgPath, pkg.Errors[0])
		}
		path, data, err := render(pkg)
		if err != nil {
			return err
		}
		if path != "" {
			outputs[path] = data
		}
	}
	paths := make([]string, 0, len(outputs))
	for path := range outputs {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		old, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if err == nil && !bytes.HasPrefix(old, []byte(generatedHeader)) {
			return fmt.Errorf("refusing to overwrite non-generated file %s", path)
		}
	}
	for _, path := range paths {
		old, _ := os.ReadFile(path)
		if bytes.Equal(old, outputs[path]) {
			continue
		}
		if err := os.WriteFile(path, outputs[path], 0644); err != nil {
			return err
		}
	}
	return nil
}

func marked(group *ast.CommentGroup) bool {
	if group == nil {
		return false
	}
	for _, c := range group.List {
		if strings.TrimSpace(c.Text) == "// generate:reset" {
			return true
		}
	}
	return false
}

func render(pkg *packages.Package) (string, []byte, error) {
	var body strings.Builder
	var output string
	for _, file := range pkg.Syntax {
		filename := pkg.Fset.Position(file.Pos()).Filename
		if filepath.Base(filename) == "reset.gen.go" {
			continue
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				if !marked(ts.Doc) && !(len(gen.Specs) == 1 && marked(gen.Doc)) {
					continue
				}
				if _, ok := ts.Type.(*ast.StructType); !ok || ts.Assign.IsValid() {
					return "", nil, fmt.Errorf("%s: generate:reset requires a defined struct", pkg.Fset.Position(ts.Pos()))
				}
				named := pkg.TypesInfo.Defs[ts.Name].Type().(*types.Named)
				for i := 0; i < named.NumMethods(); i++ {
					m := named.Method(i)
					if m.Name() == "Reset" && filepath.Base(pkg.Fset.Position(m.Pos()).Filename) != "reset.gen.go" {
						return "", nil, fmt.Errorf("%s already has a Reset method", named.Obj().Name())
					}
				}
				output = filepath.Join(filepath.Dir(filename), "reset.gen.go")
				receiver := ts.Name.Name
				if ts.TypeParams != nil {
					var params []string
					for _, field := range ts.TypeParams.List {
						for _, name := range field.Names {
							params = append(params, name.Name)
						}
					}
					receiver += "[" + strings.Join(params, ", ") + "]"
				}
				fmt.Fprintf(&body, "// Reset clears %s while retaining slices, maps and pointers.\nfunc (rs *%s) Reset() {\nif rs == nil { return }\n", ts.Name.Name, receiver)
				st := named.Underlying().(*types.Struct)
				for i := 0; i < st.NumFields(); i++ {
					field := st.Field(i)
					if field.Name() != "_" {
						emitReset(&body, "rs."+field.Name(), field.Type(), 0)
					}
				}
				body.WriteString("}\n\n")
			}
		}
	}
	if output == "" {
		return "", nil, nil
	}
	data, err := format.Source([]byte(generatedHeader + "\npackage " + pkg.Name + "\n\n" + body.String()))
	if err != nil {
		return "", nil, fmt.Errorf("format %s: %w", output, err)
	}
	return output, data, nil
}

func emitReset(out *strings.Builder, expr string, typ types.Type, depth int) {
	switch t := typ.Underlying().(type) {
	case *types.Pointer:
		fmt.Fprintf(out, "if %s != nil {\n", expr)
		emitReset(out, "(*"+expr+")", t.Elem(), depth+1)
		out.WriteString("}\n")
	case *types.Slice:
		fmt.Fprintf(out, "%s = %s[:0]\n", expr, expr)
	case *types.Map:
		fmt.Fprintf(out, "clear(%s)\n", expr)
	case *types.Struct:
		fmt.Fprintf(out, "if resetter, ok := any(&%s).(interface{ Reset() }); ok { resetter.Reset() }\n", expr)
	case *types.Array:
		index := fmt.Sprintf("i%d", depth)
		fmt.Fprintf(out, "for %s := range %s {\n", index, expr)
		emitReset(out, expr+"["+index+"]", t.Elem(), depth+1)
		out.WriteString("}\n")
	case *types.Basic:
		zero := "0"
		switch {
		case t.Info()&types.IsBoolean != 0:
			zero = "false"
		case t.Info()&types.IsString != 0:
			zero = `""`
		case t.Kind() == types.UnsafePointer:
			zero = "nil"
		}
		fmt.Fprintf(out, "%s = %s\n", expr, zero)
	default:
		if param, ok := typ.(*types.TypeParam); ok {
			fmt.Fprintf(out, "{ var zero %s; %s = zero }\n", param.Obj().Name(), expr)
		} else {
			fmt.Fprintf(out, "%s = nil\n", expr)
		}
	}
}
